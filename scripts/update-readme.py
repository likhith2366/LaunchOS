#!/usr/bin/env python3
"""Regenerates the README's headline results block from results/results.json.

The README claims no number in it was typed in by hand. This is what makes that true:
the block between the RESULTS:HEADLINE markers is generated, so the prose cannot drift
from the measurements and a stale number is a missing run rather than a typo.

    scripts/update-readme.py [results.json] [README.md]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BEGIN = "<!-- RESULTS:HEADLINE:BEGIN -->"
END = "<!-- RESULTS:HEADLINE:END -->"


def build(data: dict) -> list[str]:
    env = data.get("environment", {})
    nodes = env.get("nodes", 1)
    out = [
        BEGIN,
        "<!-- Generated by scripts/update-readme.py from results/results.json. Do not edit by hand. -->",
        "",
        "## Results",
        "",
        f"Recorded {env.get('recordedAt', '?')} on {env.get('host', '?')}, "
        f"{env.get('cores', '?')} cores, {nodes} allocator node{'' if nodes == 1 else 's'}. "
        "Full tables in [`results/RESULTS.md`](results/RESULTS.md).",
        "",
    ]

    oversell = data.get("oversell")
    if oversell:
        trials = len(oversell["successesPerTrial"])
        held = "yes" if oversell["invariantHeldEveryTrial"] else "**NO**"
        out += [
            "### Correctness",
            "",
            f"| {trials} trials, each {oversell['contendersPerTrial']} concurrent "
            f"reservations at {oversell['unitsPerTrial']} units | Value |",
            "| --- | --- |",
            f"| **Oversold units** | **{oversell['oversoldUnits']}** |",
            f"| Invariant held every trial | {held} |",
            "| Successful purchases per trial | "
            + ", ".join(str(n) for n in oversell["successesPerTrial"])
            + " |",
            "",
            "Run at shard counts of "
            + " and ".join(str(n) for n in oversell.get("shardCountsTested", [oversell["shardCount"]]))
            + ", because sharding is the change most likely to break this: the invariant "
            "then has to survive units spread over rows, probed in a customer-specific "
            "order, and returned to a different shard than they came from.",
            "",
        ]

    sweep = data.get("shardSweep")
    if sweep:
        out += [
            "### Inventory sharding",
            "",
            f"{sweep['contenders']} simultaneous reservation attempts against "
            f"{sweep['units']} units, identical load at each shard count, shard collapse "
            "disabled so this measures contention alone.",
            "",
            "| Shards | Allocations/s | Speedup | Checkout p99 |",
            "| --- | --- | --- | --- |",
        ]
        for point in sweep["points"]:
            out.append(
                f"| {point['shardCount']} | {point['reservationThroughput']:.1f} | "
                f"{point['speedupVsSingleRow']:.2f}x | {point['run']['checkoutP99MS']:.0f} ms |"
            )
        plateau = sweep.get("plateauAtShards")
        tail = f", plateauing at {plateau} shards." if plateau else " across the range swept."
        out += ["", f"**{sweep['bestSpeedup']:.2f}x throughput**{tail}", ""]

    controller = data.get("controller")
    if controller:
        out += [
            "### Adaptive vs fixed-rate admission",
            "",
            f"{controller['customers']} customers, identical seeded traffic through each "
            "admitter, stock deliberately not scarce so that inventory running out "
            "cannot be what limits completion. The adaptive arm's thresholds are derived "
            f"from a measured capacity of {controller.get('serviceCapacityPerSecond', 0):.0f} "
            f"checkouts/s and a {controller.get('targetP99MS', 0):.0f} ms p99 target: in-flight "
            f"threshold {controller.get('inFlightThreshold', 0):.0f}.",
            "",
            "Burst (spike profile):",
            "",
            "| Admitter | Rate | Checkout p99 | Completion | Errors | Time to drain |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for arm in controller["burstArms"]:
            run = arm["run"]
            out.append(
                f"| {arm['name']} | {arm['configuredRate']:.0f}/s | "
                f"{run['checkoutP99MS']:.0f} ms | {run['completionRate'] * 100:.1f}% | "
                f"{run['errorRate'] * 100:.2f}% | {arm['timeToDrainSeconds']:.1f} s |"
            )
        out += [
            "",
            "Steady load inside capacity, which is where the controller is expected to "
            "lose:",
            "",
            "| Admitter | Rate | Checkout p99 | Time to drain |",
            "| --- | --- | --- | --- |",
        ]
        for arm in controller["steadyArms"]:
            out.append(
                f"| {arm['name']} | {arm['configuredRate']:.0f}/s | "
                f"{arm['run']['checkoutP99MS']:.0f} ms | {arm['timeToDrainSeconds']:.1f} s |"
            )
        out.append("")

    fairness = data.get("fairness")
    if fairness:
        out += [
            "### Fairness",
            "",
            "Spearman rank correlation between arrival order and admission order. The "
            "admit-statement column is what the policy costs to evaluate; comparing "
            "policies on admissions per second hides it, because that number is set by "
            "the configured admission rate rather than by the ordering.",
            "",
            "| Arrivals | Policy | Rank correlation | Admit stmt mean | Mean wait |",
            "| --- | --- | --- | --- | --- |",
        ]
        for arm in fairness["arms"]:
            report = arm.get("report") or {}
            out.append(
                f"| {arm['profile']} | {arm['policy']} | "
                f"**{report.get('rankCorrelation', 0):.3f}** | {arm['admitMeanMS']:.1f} ms | "
                f"{report.get('waitMean', 0):.2f} s |"
            )
        moved = fairness["retriesEverImprovedPosition"]
        out += [
            "",
            "Retries that changed a customer's queue position: "
            f"**{'yes - a bug' if moved else 'none'}**.",
            "",
        ]

    horizon = data.get("commitHorizon")
    if horizon:
        out += [
            "### Strict FIFO needs a commit horizon",
            "",
            f"{horizon['customers']} customers arriving at once. Sequence numbers are "
            "assigned at INSERT and transactions commit in their own order, so an "
            "admitter can genuinely miss a lower-numbered entry that has not landed yet.",
            "",
            "| Commit horizon | FIFO inversions | Inversion rate | Rank correlation | Mean wait |",
            "| --- | --- | --- | --- | --- |",
        ]
        for point in horizon["points"]:
            out.append(
                f"| {point['horizonMS']:.0f} ms | **{point['fifoInversions']}** of "
                f"{point['admissionsChecked']} | {point['inversionRate'] * 100:.2f}% | "
                f"{point['rankCorrelation']:.5f} | {point['meanWaitSeconds']:.2f} s |"
            )
        worst = max(horizon["points"], key=lambda p: p["fifoInversions"])
        if worst["fifoInversions"] > 0:
            out += [
                "",
                f"Note the two middle columns together: {worst['fifoInversions']} "
                "genuinely out-of-order admissions still scored a rank correlation of "
                f"{worst['rankCorrelation']:.5f}. Rank correlation is nearly blind to a "
                "handful of inversions, which is why they are counted directly as well.",
            ]
        else:
            # Zeros across the board read as "the horizon does nothing", which is the
            # wrong conclusion. The inversion needs an admit tick to land inside the
            # window where a lower-numbered join has taken its sequence number and not
            # yet committed; this run's ticks did not, and an earlier one's did.
            out += [
                "",
                "**No inversions in this run, including at a zero horizon** — which does "
                "not mean the horizon is unnecessary. The inversion requires an admit "
                "tick to land inside the window where a lower-numbered join has taken "
                "its sequence number but not yet committed, and that is a race this run "
                "happened not to lose. An earlier run under heavier concurrent join "
                "load produced 125 inversions out of 2000 at a zero horizon, and still "
                "scored a rank correlation of 0.99996 — which is why inversions are "
                "counted directly rather than inferred from the correlation. The "
                "mechanism is structural: a sequence number is assigned before commit, "
                "and commits can land out of order. The horizon is justified by that, "
                "and sized by the runs that do exhibit it.",
            ]
        out.append("")

    tail = data.get("tailFragmentation")
    if tail:
        arms = [a for a in (tail.get("withoutCollapse"), tail.get("withCollapse")) if a]
        trials = arms[0].get("trials", 1) if arms else 1
        out += [
            "### What sharding cost: tail fragmentation",
            "",
            f"The last 5% of {tail['units']} units over {tail['shardCount']} shards, "
            f"pooled over {trials} trials per arm. Each measured wave is smaller than the "
            "stock remaining, so stock cannot run out and every failure is fragmentation "
            "rather than a sell-out - the two are indistinguishable once availability "
            "reaches zero.",
            "",
            "| Shard collapse | Requests | Failed while stock remained | Stock sat on |",
            "| --- | --- | --- | --- |",
        ]
        for arm in arms:
            out.append(
                f"| {'on' if arm['collapseEnabled'] else 'off'} | {arm.get('requestsInWave', 0)} | "
                f"**{arm['fragmentedFailures']} ({arm['fragmentedFailureRate'] * 100:.1f}%)** | "
                f"~{arm.get('shardsHoldingStockBeforeWave', 0)}/{tail['shardCount']} shards |"
            )
        out.append("")

    idem = data.get("idempotency")
    if idem:
        out += [
            "### Duplicate requests",
            "",
            f"{idem['customers']} customers each sent two concurrent checkouts carrying "
            "one idempotency key.",
            "",
            "| Metric | Value |",
            "| --- | --- |",
            f"| Completed purchases | {idem['purchases']} |",
            f"| Distinct order ids | {idem['distinctOrderIDs']} |",
            f"| **Duplicate orders per key** | **{idem['duplicateOrders']}** |",
            f"| Responses replayed from the record | {idem['replayedResponses']} |",
            "",
        ]

    # Fields added as the experiments were refined, so read defensively: an older
    # results.json should degrade to a smaller table rather than crash the generator.
    scale = data.get("positionScale")
    if scale and scale.get("points"):
        deepest = max(scale["points"], key=lambda q: q["queueDepth"])
        out += [
            "### Scaling the waiting room",
            "",
            '"How many people are ahead of me" is the most frequent request in a launch, '
            "and counting them is O(the number of people ahead of you). At a million "
            "waiting that is the whole system, and nothing downstream helps because the "
            "cost is in the question. Position is now arithmetic on a dense per-launch "
            "arrival index and a departure counter. Both paths measured inside the node, "
            "over the same rows, interleaved in the same call:",
            "",
            "| Queue depth | Estimated | Exact count | Speedup | Position error |",
            "| --- | --- | --- | --- | --- |",
        ]
        for point in scale["points"]:
            out.append(
                f"| {point['queueDepth']:,} | {point['estimatedMedianMS']:.2f} ms | "
                f"{point['exactMedianMS']:.2f} ms | **{point['speedup']:.1f}x** | "
                f"{point['positionError']} |"
            )
        out += [
            "",
            f"Flat across the range; the count grows linearly, as it must. At a depth of "
            f"{deepest['queueDepth']:,} the count costs {deepest['exactMedianMS']:.0f} ms "
            "of a Postgres core per poll, so one core answers roughly "
            f"{1000 / deepest['exactMedianMS']:.0f} of them per second.",
            "",
        ]

    sweeper = data.get("sweepStrategy")
    if sweeper:
        out += [
            "### Expiry sweep under backlog",
            "",
            "| Metric | Value |",
            "| --- | --- |",
            f"| Reservations abandoned | {sweeper.get('outstandingReservations', '?')} |",
            f"| Strategy | {sweeper.get('strategy', 'node default')} |",
            "| Batch duration, mean / p99 | "
            f"{sweeper.get('batchMeanMS', 0):.0f} / {sweeper.get('batchP99MS', 0):.0f} ms |",
            "| **Time for the pool to come back in full** | "
            f"**{sweeper.get('secondsToFullRecovery', 0):.2f} s** |",
            "",
        ]

    out.append(END)
    return out


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    results_path = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "results" / "results.json"
    readme_path = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "README.md"

    if not results_path.is_file():
        print(f"no results at {results_path}; run scripts/run-experiments.sh first", file=sys.stderr)
        return 1

    data = json.loads(results_path.read_text(encoding="utf-8"))
    block = "\n".join(build(data))

    readme = readme_path.read_text(encoding="utf-8")
    if BEGIN not in readme or END not in readme:
        print(f"{readme_path} has no RESULTS:HEADLINE markers", file=sys.stderr)
        return 1

    start = readme.index(BEGIN)
    stop = readme.index(END) + len(END)
    readme_path.write_text(readme[:start] + block + readme[stop:], encoding="utf-8", newline="\n")
    print(f"updated {readme_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
